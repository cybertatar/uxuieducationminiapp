import { lessons, questions, sections, tracks } from '../content';
import { DONATE_LINKS } from './api-types';

/**
 * «больше 130», «больше 1000» — круглое число вопросов вниз, чтобы текст не устаревал с каждым новым вопросом:
 * до 200 — до десятка, дальше — до сотни
 */
const questionsRounded = () => {
  const step = questions.length > 200 ? 100 : 10;
  return Math.floor((questions.length - 1) / step) * step;
};

/** Названия внутри фразы: «эвристики Нильсена», но «Apple HIG» и «UX» остаются как есть */
const lower = (t: string) => (/^[А-ЯЁ]/.test(t) ? t[0].toLowerCase() + t.slice(1) : t);

const joinAnd = (items: string[]) => `${items.slice(0, -1).join(', ')} и ${items.at(-1)}`;

const count = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${n} ${one}`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} ${few}`;
  return `${n} ${many}`;
};
const themes = (n: number) => count(n, 'тема', 'темы', 'тем');
const lessonsCount = () => count(lessons.length, 'урок', 'урока', 'уроков');

/** Описание в пустом чате с ботом (до 512 символов). Сначала учебник: бот теперь учит, а не только проверяет */
export const botDescription = () =>
  [
    'Учебник и тренажёр для UX/UI-дизайнеров с котом Кеглем 🐈',
    '',
    `📖 ${lessonsCount()} простым языком: пересказ NN/g, Laws of UX, Apple, Google, W3C и справки Figma с примерами из жизни`,
    `📚 ${joinAnd(sections.map((s) => lower(s.title)))}: ${themes(tracks.length)}, больше ${questionsRounded()} вопросов`,
    '🖼 Задания на макетах: найди проблему, выбери лучший вариант',
    '💡 Разбор каждого ответа, а из ошибки — сразу в нужный урок',
    '🔁 Повторение ошибок и стрик 🔥',
    '📬 Вопрос дня в чате — по желанию',
    '',
    `Бесплатно и без рекламы. Поддержать: /donate ⭐${donateLink() ? ` или картой ${donateLink()}` : ''}`,
  ].join('\n');

/** Ссылка на донат без https://: Telegram сам делает её кликабельной, а в описаниях каждый символ на счету */
const donateLink = () => DONATE_LINKS[0]?.url.replace(/^https?:\/\//, '');

/** Короткое описание — поле «about» в профиле бота (до 120 символов). Это его видят все, кто уже начал чат */
export const botShortDescription = () => {
  const link = donateLink();
  return `Уроки UX/UI простым языком и тесты по UX, гайдлайнам и Figma 🐈${link ? ` Поддержать: ${link}` : ''}`;
};

