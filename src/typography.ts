/**
 * Неразрывные пробелы по правилам русской типографики: короткое слово не висит в конце строки,
 * тире не начинает строку, число не отрывается от слова. Браузер переносит строки сам, поэтому
 * склеиваем такие места заранее — в CSS этого не сделать.
 */

const NBSP = ' ';

/** Предлоги, союзы и частицы длиннее двух букв, которые тоже не должны оставаться в конце строки */
const SHORT = 'для|без|при|про|под|над|обо|ото|как|или|что|чем|это|все|всё|его|еще|ещё|уже|нет|так|тут|там';

/** Частицы держатся за предыдущее слово, а не за следующее: «то же», «было бы» */
const PARTICLES = '(?:ли|ль|же|ж|бы|б)';

/** Короткое слово и обычный пробел за ним: «в тренажёре», «и таким». Слово перед ним не захватываем, чтобы цепочки «и в то» склеивались за один проход */
const AFTER_SHORT = new RegExp(`(?<=^|[\\s(«„"])(?!${PARTICLES}[^а-яё])([а-яёa-z]{1,2}|${SHORT})[^\\S\\u00A0]+`, 'giu');
const BEFORE_PARTICLE = new RegExp(`\\s+(${PARTICLES})(?=[\\s.,!?:;…)»]|$)`, 'giu');

export function typo(text: string): string {
  return text
    .replace(AFTER_SHORT, `$1${NBSP}`)
    .replace(BEFORE_PARTICLE, `${NBSP}$1`)
    .replace(/\s+—/g, `${NBSP}—`)
    .replace(/(\d)\s+(?=[^\s\d])/g, `$1${NBSP}`);
}
